-- Jalankan sekali di Supabase: SQL Editor > New query > Run
create table if not exists public.films (
  id bigint generated by default as identity primary key,
  title text not null,
  description text default '',
  genre text not null,
  country text default 'Internasional',
  year integer,
  poster_url text default '',
  video_type text not null check (video_type in ('youtube', 'mp4')),
  video_url text not null,
  source_url text not null,
  rights_type text not null check (rights_type in ('youtube_embed', 'licensed')),
  rights_note text not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

alter table public.films enable row level security;

-- Akses database langsung dari browser ditutup.
-- Aplikasi mengakses tabel melalui API server Next.js dengan service role key.
revoke all on public.films from anon, authenticated;
